// Package certreservation holds the record of a certificate that has
// been prepared for a Comb that has not joined the Colony yet.
//
// WHY THIS EXISTS. A public certificate authority validates a
// hostname, not a machine's right to be a member of this Colony. The
// two questions are separate and must stay separate: the CA answers
// "does the holder of this private key control host2.lab2.apiary.work",
// and Apiary answers "is this Comb one of ours, and do its peers
// recognise it". A certificate issued for a hostname is not a grant of
// membership, and a membership decision is not a substitute for a
// valid certificate.
//
// The workflow this package exists to support is the offline
// preparation one. Host 1 is asked to issue a certificate for Host 2
// BEFORE Host 2 exists on the network. That needs three things that
// did not exist before:
//
//   - A RESERVATION. Something has to say "a certificate for
//     host2.lab2.apiary.work is prepared, and it belongs to the Comb
//     that later proves it is host2". The reservation is that record.
//
//   - A BOOTSTRAP KEY. ACME never delivers a private key: the key is
//     the requester's, and the CA only signs a CSR made with it. So a
//     certificate prepared before the joiner exists is a certificate
//     whose private key was generated by the PREPARER. That key is a
//     temporary secret with a temporary owner, and this package is
//     explicit about that rather than pretending a prepared pair is
//     indistinguishable from a locally generated one.
//
//   - A TRANSFER AUTHORIZATION. Holding a reservation identifier is
//     not authority to collect the material. The join attestation
//     (ADR-0147's first code and second PIN) is what binds a
//     reservation to the actual joining node, and the transfer is
//     refused for a request that did not carry that binding.
//
// THREE PROPERTIES THIS PACKAGE ENFORCES, each of which is a refusal
// rather than a warning, because each of them prevents a silent
// failure:
//
//  1. A reservation is NOT a member. A reservation never appears in
//     the peer trust store and never implies membership. It is a
//     pending intent, and the only thing that promotes it is the
//     join flow's own authorization.
//
//  2. The bootstrap key is retired, not just superseded. A joiner
//     that adopts a prepared pair is expected to generate its own key
//     and obtain its own replacement certificate. Until it does, the
//     preparer's copy of the bootstrap key is a secret that two
//     machines hold, which is the whole cost of this mode.
//
//  3. The transfer is single-use and time-bounded. A reservation
//     that has been delivered cannot be delivered again, and one
//     whose window has closed cannot be delivered at all.
//
// The package deliberately holds NO key material of its own and
// performs no I/O: it defines the record, its lifecycle, and the
// checks that a delivery must pass. Where the bytes live is the
// caller's business, and this package's own comments refuse to
// pretend otherwise.
package certreservation

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"fmt"
	"strings"
	"time"
)

// Lifecycle states of a reservation.
//
// The states are deliberately few and strictly ordered. A reservation
// moves forward and never backward: a withdrawn reservation cannot
// become prepared again, and a delivered one cannot become prepared
// again either. That is what makes "the same reservation cannot be
// used twice" a property of the state machine rather than a check
// each caller has to remember to write.
const (
	// StatePrepared means the certificate has been obtained and the
	// pair is held, ready to be delivered to the joining Comb.
	StatePrepared = "prepared"

	// StateDelivered means the pair has been delivered to the joining
	// Comb over the authenticated join channel and acknowledged. The
	// reservation cannot be delivered again.
	StateDelivered = "delivered"

	// StateAdopted means the joining Comb has installed the prepared
	// pair and taken ownership of it.
	StateAdopted = "adopted"

	// StateRetired means the bootstrap key is retired and the
	// reservation is spent. A replacement certificate has been
	// obtained by the joiner itself.
	StateRetired = "retired"

	// StateWithdrawn means the operator cancelled the reservation
	// before it was delivered.
	StateWithdrawn = "withdrawn"

	// StateExpired means the reservation's window closed before it was
	// delivered.
	StateExpired = "expired"
)

// DefaultTTL is how long a reservation stays deliverable.
//
// It is bounded on purpose. A prepared pair sits on the preparing
// Comb holding a private key for a machine that has not arrived yet,
// and an unbounded reservation is an unbounded wait. An hour is long
// enough to cover a window in which an operator prepares a host and
// then brings it up, and short enough that a forgotten reservation
// expires rather than sitting in a protected store indefinitely.
const DefaultTTL = time.Hour

// Errors returned by this package. They are exported because a caller
// must be able to tell "this reservation is gone" from "this
// reservation is wrong", and both from "the material you handed me
// does not match".
var (
	// ErrNotFound means no reservation exists with that identifier.
	ErrNotFound = errors.New("certreservation: no such reservation")

	// ErrExpired means the reservation's delivery window has closed.
	ErrExpired = errors.New("certreservation: the reservation's delivery window has closed")

	// ErrAlreadyDelivered means the reservation has already been
	// delivered. A second delivery attempt is refused, not ignored.
	ErrAlreadyDelivered = errors.New("certreservation: the reservation has already been delivered")

	// ErrWithdrawn means the operator cancelled the reservation.
	ErrWithdrawn = errors.New("certreservation: the reservation was withdrawn")

	// ErrWrongRecipient means the delivery attempt was not made by,
	// or for, the Comb the reservation is bound to.
	ErrWrongRecipient = errors.New("certreservation: the reservation is not bound to this node")

	// ErrNotBound means the reservation has not yet been bound to a
	// joining node, so nobody may collect it.
	ErrNotBound = errors.New("certreservation: the reservation is not bound to a joining node yet")

	// ErrReplay means the delivery carries a token that does not
	// match the one recorded for this reservation.
	ErrReplay = errors.New("certreservation: the delivery token does not match this reservation")

	// ErrKeyMismatch means the delivered private key does not match
	// the delivered certificate's public key.
	ErrKeyMismatch = errors.New("certreservation: the private key does not match the certificate")

	// ErrNameMismatch means the certificate does not cover the name
	// the reservation was made for.
	ErrNameMismatch = errors.New("certreservation: the certificate does not cover the reserved name")
)

// Reservation is the record of one prepared certificate.
//
// It is a plain struct on purpose. It carries no key material and no
// envelope: this is the METADATA of a preparation, and the bytes it
// refers to live in whatever protected store the caller uses. Keeping
// those two apart is what lets this record be replicated, logged, or
// rendered by an operator without becoming a secret.
type Reservation struct {
	// ID is the reservation identifier. It is generated by
	// NewReservation and is unguessable, because it is one half of
	// the "knowing the hostname or reservation identifier does not
	// authorize retrieval" rule: it identifies a reservation, it does
	// not authorize collecting one.
	ID string

	// NodeID is the Comb this reservation is bound to. It is EMPTY
	// until the join flow binds it, and a reservation with an empty
	// NodeID is deliverable to nobody. That is the whole point of
	// the binding step: before the joining Comb proves its identity
	// through the join attestation, there is no node this
	// reservation could honestly be for.
	NodeID string

	// RequestID is the join request this reservation belongs to. It
	// is the same value the join flow carries, and it is what makes
	// the binding checkable rather than a matter of trust: the
	// delivery is refused unless the join request that presents it
	// is the request the reservation was prepared for.
	RequestID string

	// FQDN is the name the certificate was issued for.
	FQDN string

	// Fingerprint is the hostcert-style digest of the prepared
	// certificate's public key, so the binding between a reservation
	// and a specific certificate is recorded rather than assumed.
	Fingerprint string

	// DeliveryToken is the secret that authorizes collection of the
	// prepared material.
	//
	// It is distinct from the reservation's identity on purpose. The
	// reservation ID is public - it may be shown to an operator, and
	// it names a preparation - while this token is what proves the
	// presenter is the Comb the reservation was bound to. A tool that
	// could type a token is a tool that could type a lie, so the token
	// is generated here, never derived from a name, and compared in
	// constant time.
	DeliveryToken string

	// CertificatePEM is the prepared certificate chain.
	CertificatePEM string

	// CreatedAtUnix / ExpiresAtUnix bound the delivery window, in
	// whole Unix seconds like every other replicated timestamp in
	// this codebase.
	CreatedAtUnix int64
	ExpiresAtUnix int64

	// State is the lifecycle state.
	State string

	// DeliveredAtUnix is when the pair was delivered, zero if it was
	// not.
	DeliveredAtUnix int64

	// BoundAtUnix is when the reservation was bound to a joining
	// node, zero if it was not.
	BoundAtUnix int64
}

// Expired reports whether the delivery window has closed as of now.
func (r *Reservation) Expired(now time.Time) bool {
	return r.ExpiresAtUnix > 0 && now.Unix() > r.ExpiresAtUnix
}

// Deliverable reports whether the reservation can still be delivered.
//
// Every reason it cannot be is named, because "cannot deliver" is a
// message an operator has to act on and the actions differ: an
// expired reservation needs a new preparation, a withdrawn one was
// cancelled deliberately, and a delivered one needs the joiner to
// finish adopting it.
func (r *Reservation) Deliverable(now time.Time) error {
	switch r.State {
	case StatePrepared:
	case StateDelivered:
		return ErrAlreadyDelivered
	case StateWithdrawn:
		return ErrWithdrawn
	case StateAdopted, StateRetired:
		return ErrAlreadyDelivered
	default:
		return fmt.Errorf("certreservation: the reservation is in the unknown state %q", r.State)
	}
	if r.Expired(now) {
		return ErrExpired
	}
	return nil
}

// NewReservation creates a prepared reservation with a fresh
// identifier.
//
// The identifier is 32 random bytes, base64url-encoded without
// padding. It is generated here rather than derived from the name or
// the node, because the identifier is what a reservation is looked up
// by and a predictable one would let a third party probe for
// preparations.
func NewReservation(fqdn, certificatePEM, fingerprint string, ttl time.Duration) (*Reservation, error) {
	if strings.TrimSpace(fqdn) == "" {
		return nil, fmt.Errorf("certreservation: the reserved FQDN must be set")
	}
	if strings.TrimSpace(certificatePEM) == "" {
		return nil, fmt.Errorf("certreservation: the prepared certificate must be set")
	}
	if strings.TrimSpace(fingerprint) == "" {
		return nil, fmt.Errorf("certreservation: the prepared certificate's fingerprint must be set")
	}
	if ttl <= 0 {
		ttl = DefaultTTL
	}
	raw := make([]byte, 32)
	if _, err := rand.Read(raw); err != nil {
		return nil, fmt.Errorf("certreservation: generating a reservation identifier: %w", err)
	}
	tokenRaw := make([]byte, 32)
	if _, err := rand.Read(tokenRaw); err != nil {
		return nil, fmt.Errorf("certreservation: generating a delivery token: %w", err)
	}
	now := time.Now().UTC()
	return &Reservation{
		ID:             base64.RawURLEncoding.EncodeToString(raw),
		DeliveryToken:  base64.RawURLEncoding.EncodeToString(tokenRaw),
		FQDN:           strings.TrimSpace(fqdn),
		CertificatePEM: certificatePEM,
		Fingerprint:    strings.TrimSpace(fingerprint),
		CreatedAtUnix:  now.Unix(),
		ExpiresAtUnix:  now.Add(ttl).Unix(),
		State:          StatePrepared,
	}, nil
}

// Bind binds this reservation to the joining node and the join
// request that proves the joiner's identity.
//
// It is the step the whole design turns on, and it is refused unless
// both values are present. A reservation that is not bound is
// deliverable to nobody, because there is no honest answer to "is this
// the Comb I prepared this for?" until the join attestation has
// answered it.
//
// Binding is refused a second time. A reservation bound to one join
// request cannot be re-bound to another, because that would let a
// second requester claim a preparation made for the first - and the
// prepared material is a private key, so a re-bind is a key handover
// to the wrong machine.
func (r *Reservation) Bind(nodeID, requestID string, now time.Time) error {
	if strings.TrimSpace(nodeID) == "" {
		return fmt.Errorf("certreservation: the joining node's ID must be set")
	}
	if strings.TrimSpace(requestID) == "" {
		return fmt.Errorf("certreservation: the join request ID must be set")
	}
	if r.NodeID != "" {
		return fmt.Errorf("certreservation: the reservation is already bound to node %q for request %q; a preparation is made for one joining node",
			r.NodeID, r.RequestID)
	}
	if r.State != StatePrepared {
		return fmt.Errorf("certreservation: a reservation in the state %q cannot be bound", r.State)
	}
	r.NodeID = strings.TrimSpace(nodeID)
	r.RequestID = strings.TrimSpace(requestID)
	r.BoundAtUnix = now.UTC().Unix()
	return nil
}

// AuthorizeDelivery checks that this delivery attempt is allowed to
// collect the prepared material, and returns the reservation.
//
// The checks are in the order an operator would want them explained,
// and each refusal names itself:
//
//   - The reservation must exist.
//   - It must be in a deliverable state, and its window must be open.
//   - It must be bound to a node, and to THAT node.
//   - The join request presenting the delivery must be the request the
//     reservation was prepared for.
//   - The delivery token must match, in constant time.
//
// The token check is last and is constant-time because it is the only
// comparison here whose failure must not leak how much of the token
// was right.
func (r *Reservation) AuthorizeDelivery(nodeID, requestID, token string, now time.Time) error {
	if err := r.Deliverable(now); err != nil {
		return err
	}
	if r.NodeID == "" {
		return ErrNotBound
	}
	if subtle.ConstantTimeCompare([]byte(nodeID), []byte(r.NodeID)) != 1 {
		return ErrWrongRecipient
	}
	if subtle.ConstantTimeCompare([]byte(requestID), []byte(r.RequestID)) != 1 {
		return ErrWrongRecipient
	}
	if r.DeliveryToken == "" {
		return fmt.Errorf("certreservation: the reservation carries no delivery token; a reservation with no token cannot be delivered")
	}
	if subtle.ConstantTimeCompare([]byte(token), []byte(r.DeliveryToken)) != 1 {
		return ErrReplay
	}
	return nil
}

// MarkDelivered records that the pair was delivered.
//
// The state moves to delivered, which is what makes a second delivery
// impossible: Deliverable refuses anything that is not prepared.
func (r *Reservation) MarkDelivered(now time.Time) error {
	if err := r.Deliverable(now); err != nil {
		return err
	}
	r.State = StateDelivered
	r.DeliveredAtUnix = now.UTC().Unix()
	return nil
}

// MarkAdopted records that the joining Comb installed the prepared
// pair and took ownership of it.
func (r *Reservation) MarkAdopted(now time.Time) error {
	if r.State != StateDelivered {
		return fmt.Errorf("certreservation: a reservation in the state %q cannot be adopted; it must be delivered first", r.State)
	}
	r.State = StateAdopted
	return nil
}

// MarkRetired records that the bootstrap key is retired.
//
// This is the step that ends the exposure the prepared mode creates:
// after it, the preparer's copy of the bootstrap key is worthless and
// can be destroyed, and the joiner holds a key it generated itself.
func (r *Reservation) MarkRetired() error {
	if r.State != StateAdopted {
		return fmt.Errorf("certreservation: a reservation in the state %q cannot be retired; it must be adopted first", r.State)
	}
	r.State = StateRetired
	return nil
}

// Withdraw cancels a reservation before it is delivered.
func (r *Reservation) Withdraw() error {
	if r.State != StatePrepared {
		return fmt.Errorf("certreservation: a reservation in the state %q cannot be withdrawn", r.State)
	}
	r.State = StateWithdrawn
	return nil
}
